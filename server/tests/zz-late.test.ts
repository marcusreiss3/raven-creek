import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { eq } from 'drizzle-orm';
import request from 'supertest';
import { db, schema, pool } from '../src/db/index.js';
import { boot, connect, makePlayer, startServer, wait } from './helpers.js';
import { finishPrologue, prologueRunning, _resetPrologueMemory, loadPrologue, joinPrologueLate, isPrologueMember, prologueLatecomers } from '../src/game/services/prologue.js';
import { startPrologueNow } from '../src/game/services/prologueControl.js';
import { resetServerStatusForTests, playBlock } from '../src/game/services/serverStatus.js';
let srv: Awaited<ReturnType<typeof startServer>>;
beforeAll(async () => { await boot(); await resetServerStatusForTests(); _resetPrologueMemory(); srv = await startServer(); await loadPrologue(); });
afterAll(async () => { if (prologueRunning()) await finishPrologue(); await resetServerStatusForTests(); await srv.close(); await pool.end(); });
describe('entrada atrasada no Dia 1', () => {
  it('a equipe coloca um atrasado no grupo da mesma profissão', async () => {
    const a = await makePlayer({ profession: 'doctor' }); const b = await makePlayer({ profession: 'nurse' });
    const sa = await connect(srv.url, a.cookie); const sb = await connect(srv.url, b.cookie);
    await wait(200);
    await startPrologueNow(1);
    const late = await makePlayer({ profession: 'doctor' });
    await db.update(schema.characters).set({ approved: false }).where(eq(schema.characters.id, late.character.id));
    const me = await request(srv.url).get('/api/auth/me').set('Cookie', late.cookie);
    expect(me.body.block.reason).toBe('prologue');
    const lc = await prologueLatecomers([]);
    expect(lc.map((x) => x.id)).toContain(late.character.id);
    expect(playBlock('player', { id: late.character.id, approved: false })?.reason).toBe('prologue');
    const r = await joinPrologueLate(late.character.id);
    expect(r.ok).toBe(true);
    expect(isPrologueMember(late.character.id)).toBe(true);
    expect(playBlock('player', { id: late.character.id, approved: true })).toBeNull();
    const [m] = await db.select().from(schema.prologueMembers).where(eq(schema.prologueMembers.characterId, late.character.id));
    const [ma] = await db.select().from(schema.prologueMembers).where(eq(schema.prologueMembers.characterId, a.character.id));
    expect(m.groupId).toBe(ma.groupId);
    expect(Object.keys(m.flags).some((k) => k.startsWith('fam:'))).toBe(true);
    const evs = await db.select().from(schema.prologueEvents).where(eq(schema.prologueEvents.characterId, late.character.id));
    expect(evs.some((e) => String((e.payload as any).text ?? '').includes('atrasado'))).toBe(true);
    const [c] = await db.select().from(schema.characters).where(eq(schema.characters.id, late.character.id));
    expect(c.approved).toBe(true);
    await expect(joinPrologueLate(late.character.id)).rejects.toThrow(/já está/);
    sa.close(); sb.close();
  });
});
